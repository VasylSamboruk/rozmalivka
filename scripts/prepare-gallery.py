def js_items(items):
    lines = []
    for item in items:
        lines.append(
            "  { src: '%s', w: %d, h: %d, type: '%s' },"
            % (item["src"], item["w"], item["h"], item.get("type", "image"))
        )
    return "\n".join(lines)


