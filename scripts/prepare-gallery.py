def save_webp(src, dest, max_w, quality):
    with Image.open(src) as im:
        im = im.convert("RGB")
        w, h = im.size
        if w > max_w:
            h = max(1, int(h * max_w / w))
            w = max_w
            im = im.resize((w, h), Image.Resampling.LANCZOS)
        im.save(dest, "WEBP", quality=quality, method=6)
        return w, h


covers = []
for name in sorted(os.listdir(ROOT)):
    folder = os.path.join(ROOT, name)
    if not os.path.isdir(folder) or name in SKIP:
        continue
    src = None
    for stem in ("1", "01", "001"):
        for ext in (".jpg", ".jpeg", ".png", ".webp", ".JPG", ".JPEG", ".PNG"):
            candidate = os.path.join(folder, stem + ext)
            if os.path.isfile(candidate):
                src = candidate
                break
        if src:
            break
    if not src:
        continue
    idx = len(covers) + 1
    dest_name = f"cover-{idx:02d}.webp"
    dest = os.path.join(OUT_COVERS, dest_name)
    w, h = save_webp(src, dest, 1000, 76)
    covers.append({"src": f"/covers/{dest_name}", "w": w, "h": h, "type": "image"})
    print("cover", dest_name, os.path.getsize(dest))

real_srcs = []
for dirpath, _, files in os.walk(ROOT):
    base = os.path.basename(dirpath)
    if base in SKIP:
        continue
    if "\\rozmal" in dirpath or dirpath.endswith("rozmal"):
        continue
    hits = []
    for f in files:
        lower = f.lower()
        if lower.endswith("_n.webp") or lower.endswith("_n.jpg"):
            path = os.path.join(dirpath, f)
            hits.append((os.path.getsize(path), path))
    hits.sort(reverse=True)
    if hits:
        real_srcs.append(hits[0])

real_srcs.sort(reverse=True)
real = []
